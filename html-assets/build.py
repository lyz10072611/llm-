# ── Wikilink preprocessing ───────────────────────────────────────
WIKILINK_RE = re.compile(r"\[\[([^\]]+)\]\]")
FENCE_OPEN_RE = re.compile(r"^ {0,3}(`{3,}|~{3,})(.*)$")


def markdown_segments(body: str) -> Iterator[tuple[bool, str]]:
    """Yield (is_fenced_code, original_text), preserving fences without placeholders."""
    chunk: list[str] = []
    closing: re.Pattern[str] | None = None
    for line in body.splitlines(keepends=True):
        content = line.rstrip("\r\n")
        if closing is not None:
            chunk.append(line)
            if closing.fullmatch(content):
                yield True, "".join(chunk)
                chunk = []
                closing = None
            continue

        opening = FENCE_OPEN_RE.match(content)
        if opening and not (opening[1][0] == "`" and "`" in opening[2]):
            if chunk:
                yield False, "".join(chunk)
            fence = opening[1]
            closing = re.compile(r" {0,3}" + re.escape(fence[0]) + "{" + str(len(fence)) + r",}[ \t]*")
            chunk = [line]
        else:
            chunk.append(line)
    if chunk:
        yield closing is not None, "".join(chunk)


def transform_outside_fenced_code(body: str, transform: Callable[[str], str]) -> str:
    """Apply transform to Markdown prose while preserving fenced code verbatim."""
    return "".join(
        text if fenced else transform(text)
        for fenced, text in markdown_segments(body)
    )


def transform_outside_inline_code(body: str, transform: Callable[[str], str]) -> str:
    """Apply transform outside matching Markdown backtick code spans."""
    output: list[str] = []
    cursor = 0
    while opening := re.search(r"`+", body[cursor:]):
        opening_start = cursor + opening.start()
        opening_end = cursor + opening.end()
        delimiter = opening.group(0)
        closing = re.search(
            rf"(?<!`){re.escape(delimiter)}(?!`)",
            body[opening_end:],
        )
        if closing is None:
            break
        closing_end = opening_end + closing.end()
        output.append(transform(body[cursor:opening_start]))
        output.append(body[opening_start:closing_end])
        cursor = closing_end
    output.append(transform(body[cursor:]))
    return "".join(output)


def rewrite_wikilinks(body: str, resolver: Resolver, from_cat: str | None) -> str:
    def repl(m: re.Match) -> str:
        target = m.group(1).strip()
        label = target
        if "|" in target:
            target, label = target.split("|", 1)
            target = target.strip()
            label = label.strip()
        href = resolver.href(target, from_cat=from_cat)
        if href:
            return f'<a class="wikilink" href="{href}">{htmllib.escape(label)}</a>'
        return f'<span class="wikilink wikilink-missing" title="未建页：{htmllib.escape(target)}">{htmllib.escape(label)}</span>'

    return "".join(text if fenced else WIKILINK_RE.sub(repl, text) for fenced, text in markdown_segments(body))


def page_anchor(stem: str) -> str:
    return f"page-{slugify(stem)}"


def rewrite_topic_wikilinks(body: str, resolver: Resolver, included: set[str]) -> str:
    """Rewrite wiki links for a self-contained book without local HTML links."""
    included_lower = {stem.lower() for stem in included}

    def repl(m: re.Match) -> str:
        raw_target = m.group(1).strip()
        target_with_fragment = raw_target
        label: str | None = None
        if "|" in target_with_fragment:
            target_with_fragment, label = target_with_fragment.split("|", 1)
            target_with_fragment = target_with_fragment.strip()
            label = label.strip()

        target, separator, fragment = target_with_fragment.partition("#")
        target = target.strip()
        fragment = fragment.strip()
        readable = label or target
        readable = htmllib.escape(readable).replace("[", "\\[").replace("]", "\\]")
        resolved = resolver.resolve(target)
        if resolved:
            _category, stem = resolved
            if stem.lower() in included_lower:
                anchor = page_anchor(stem)
                if separator and fragment:
                    anchor = f"{anchor}--{slugify(fragment)}"
                return f"[{readable}](#{anchor})"
        return readable

    return transform_outside_fenced_code(
        body,
        lambda prose: transform_outside_inline_code(
            prose,
            lambda text: WIKILINK_RE.sub(repl, text),
        ),
    )


def rewrite_topic_image_destinations(body: str, source_dir: Path) -> str:
    """Resolve page-relative Markdown images for the temporary topic book."""

    def unescape_destination(destination: str) -> str:
        punctuation = "!\"#$%&'()*+,-./:;<=>?@[\\]^_`{|}~"
        output: list[str] = []
        cursor = 0
        while cursor < len(destination):
            if (
                destination[cursor] == "\\"
                and cursor + 1 < len(destination)
                and destination[cursor + 1] in punctuation
            ):
                cursor += 1
            output.append(destination[cursor])
            cursor += 1
        return "".join(output)

    def resolve_destination(raw_destination: str) -> str:
        destination = unescape_destination(raw_destination)
        parsed = urlsplit(destination)
        if destination.startswith("#") or parsed.scheme or parsed.netloc:
            return raw_destination

        absolute_uri = (source_dir / unquote(parsed.path)).resolve().as_uri()
        if parsed.query:
            absolute_uri += f"?{parsed.query}"
        if parsed.fragment:
            absolute_uri += f"#{parsed.fragment}"
        return absolute_uri

    def destination_span(text: str, start: int) -> tuple[int, int, int] | None:
        cursor = start + 2
        bracket_depth = 0
        while cursor < len(text):
            char = text[cursor]
            if char == "\\" and cursor + 1 < len(text):
                cursor += 2
                continue
            if char == "[":
                bracket_depth += 1
            elif char == "]":
                if bracket_depth == 0:
                    break
                bracket_depth -= 1
            cursor += 1
        if cursor + 1 >= len(text) or text[cursor + 1] != "(":
            return None

        cursor += 2
        while cursor < len(text) and text[cursor] in " \t":
            cursor += 1
        angled = cursor < len(text) and text[cursor] == "<"
        if angled:
            destination_start = cursor + 1
            cursor = destination_start
            while cursor < len(text):
                if text[cursor] == "\\" and cursor + 1 < len(text):
                    cursor += 2
                    continue
                if text[cursor] == ">":
                    break
                if text[cursor] == "\n":
                    return None
                cursor += 1
            if cursor >= len(text):
                return None
            destination_end = cursor
            cursor += 1
        else:
            destination_start = cursor
            parenthesis_depth = 0
            while cursor < len(text):
                char = text[cursor]
                if char == "\\" and cursor + 1 < len(text):
                    cursor += 2
                    continue
                if char == "(":
                    parenthesis_depth += 1
                elif char == ")":
                    if parenthesis_depth == 0:
                        break
                    parenthesis_depth -= 1
                elif char in " \t" and parenthesis_depth == 0:
                    break
                elif char == "\n":
                    return None
                cursor += 1
            if cursor >= len(text) or parenthesis_depth != 0:
                return None
            destination_end = cursor

        title_separator = cursor
        while cursor < len(text) and text[cursor] in " \t":
            cursor += 1
        if cursor < len(text) and text[cursor] == ")":
            return destination_start, destination_end, cursor + 1
        if cursor == title_separator or cursor >= len(text):
            return None

        delimiter = text[cursor]
        if delimiter in "\"'":
            cursor += 1
            while cursor < len(text):
                if text[cursor] == "\\" and cursor + 1 < len(text):
                    cursor += 2
                    continue
                if text[cursor] == delimiter:
                    cursor += 1
                    break
                if text[cursor] == "\n":
                    return None
                cursor += 1
            else:
                return None
        elif delimiter == "(":
            title_depth = 1
            cursor += 1
            while cursor < len(text) and title_depth:
                if text[cursor] == "\\" and cursor + 1 < len(text):
                    cursor += 2
                    continue
                if text[cursor] == "(":
                    title_depth += 1
                elif text[cursor] == ")":
                    title_depth -= 1
                elif text[cursor] == "\n":
                    return None
                cursor += 1
            if title_depth:
                return None
        else:
            return None

        while cursor < len(text) and text[cursor] in " \t":
            cursor += 1
        if cursor >= len(text) or text[cursor] != ")":
            return None
        return destination_start, destination_end, cursor + 1

    def rewrite_prose(text: str) -> str:
        output: list[str] = []
        output_cursor = 0
        search_cursor = 0
        while (image_start := text.find("![", search_cursor)) >= 0:
            span = destination_span(text, image_start)
            if span is None:
                search_cursor = image_start + 2
                continue
            destination_start, destination_end, image_end = span
            output.append(text[output_cursor:destination_start])
            output.append(resolve_destination(text[destination_start:destination_end]))
            output_cursor = destination_end
            search_cursor = image_end
        output.append(text[output_cursor:])
        return "".join(output)

    return transform_outside_fenced_code(
        body,
        lambda prose: transform_outside_inline_code(
            prose,
            rewrite_prose,
        ),
    )


# ── TOC extraction ───────────────────────────────────────────────
HEADING_RE = re.compile(r"^(#{1,6})[ \t]+([^\r\n]+?)[ \t]*(?=\r?$)", re.MULTILINE)


def slugify(s: str) -> str:
    s = re.sub(r"[<>&\"']+", "", s)
    s = re.sub(r"\s+", "-", s.strip().lower())
    s = re.sub(r"[^a-z0-9\u4e00-\u9fa5\-_]", "", s)
    return s[:80] or "section"


def extract_toc(body: str) -> list[tuple[int, str, str]]:
    """Return [(level, text, slug)] for h2/h3 (skip h1; it's the page title)."""
    toc = []
    seen: dict[str, int] = {}
    headings = (
        match
        for fenced, text in markdown_segments(body)
        if not fenced
        for match in HEADING_RE.finditer(text)
    )
    for m in headings:
        hashes, text = m.group(1), m.group(2)
        level = len(hashes)
        if level < 2 or level > 3:
            continue
        slug = slugify(text)
        if slug in seen:
            seen[slug] += 1
            slug = f"{slug}-{seen[slug]}"
        else:
            seen[slug] = 1
        toc.append((level, text, slug))
    return toc


def inject_heading_ids(body: str, namespace: str | None = None) -> str:
    """Add {#slug} to h2/h3 so python-markdown's toc extension picks them up."""
    seen: dict[str, int] = {}

    def repl(m: re.Match) -> str:
        hashes, text = m.group(1), m.group(2)
        level = len(hashes)
        if level < 2 or level > 3:
            return m.group(0)
        # Strip wikilink syntax for slugification only
        plain = WIKILINK_RE.sub(r"\1", text)
        slug = slugify(plain)
        if slug in seen:
            seen[slug] += 1
            slug = f"{slug}-{seen[slug]}"
        else:
            seen[slug] = 1
        if namespace:
            slug = f"{namespace}--{slug}"
        return f"{hashes} {text} {{#{slug}}}"

    return transform_outside_fenced_code(body, lambda prose: HEADING_RE.sub(repl, prose))


