def collect_graph_data(resolver: Resolver, descriptions: dict[str, str] | None = None) -> dict[str, object]:
    descriptions = descriptions or {}
    nodes: dict[str, GraphNode] = {}
    edges_by_pair: dict[tuple[str, str], str] = {}

    for cat in CATEGORIES:
        src_dir = WIKI / cat
        if not src_dir.is_dir():
            continue
        for md_path in sorted(src_dir.glob("*.md")):
            page = load_page(md_path, cat)
            node_id = md_path.stem
            href = f"{cat}/{node_id}.html"
            nodes[node_id] = GraphNode(
                id=node_id,
                title=page.title,
                category=cat,
                category_label=CATEGORY_LABELS.get(cat, cat),
                href=href,
                tags=page.fm.tags,
                date=page.fm.date,
                description=descriptions.get(href, ""),
            )

            page_edges: dict[tuple[str, str], str] = {}
            for raw in WIKILINK_RE.findall(page.body_md):
                resolved = resolver.resolve(raw)
                if not resolved:
                    continue
                _target_cat, target_stem = resolved
                if target_stem != node_id:
                    page_edges.setdefault((node_id, target_stem), "wikilink")
            for raw in page.fm.related:
                resolved = resolver.resolve(raw)
                if not resolved:
                    continue
                _target_cat, target_stem = resolved
                if target_stem != node_id:
                    page_edges[(node_id, target_stem)] = "related"
            edges_by_pair.update(page_edges)

    inbound: dict[str, set[str]] = {node_id: set() for node_id in nodes}
    outbound: dict[str, set[str]] = {node_id: set() for node_id in nodes}
    for source, target in edges_by_pair:
        if source not in nodes or target not in nodes:
            continue
        outbound[source].add(target)
        inbound[target].add(source)

    for node_id, node in nodes.items():
        node.inbound = len(inbound[node_id])
        node.outbound = len(outbound[node_id])
        node.degree = len(inbound[node_id] | outbound[node_id])

    edges = [
        GraphEdge(source=source, target=target, kind=kind)
        for (source, target), kind in sorted(edges_by_pair.items())
        if source in nodes and target in nodes
    ]
    return {
        "nodes": [node.__dict__ for node in sorted(nodes.values(), key=lambda n: (n.category, n.title.lower()))],
        "edges": [edge.__dict__ for edge in edges],
        "categories": [
            {
                "id": cat,
                "label": CATEGORY_LABELS.get(cat, cat),
                "count": sum(1 for node in nodes.values() if node.category == cat),
            }
            for cat in CATEGORIES
        ],
    }


def build_topic_groups(pages: list[PageMeta]) -> list[dict[str, object]]:
    by_stem = {p.stem: p for p in pages}
    groups: list[dict[str, object]] = []
    for cfg in TOPIC_GROUPS:
        tagset = cfg["tags"]
        preferred_stems = cfg["preferred"]
        preferred_set = set(preferred_stems)
        matches = [
            p for p in pages
            if tagset.intersection(set(p.tags))
            or any(token in p.title.lower() for token in tagset)
            or p.stem in preferred_set
        ]
        unique: dict[str, PageMeta] = {p.href: p for p in matches}
        ordered = [by_stem[s] for s in preferred_stems if s in by_stem]
        ordered.extend(
            sorted(
                (p for p in unique.values() if p.stem not in preferred_set),
                key=lambda p: (p.category != "analysis", p.title.lower()),
            )
        )
        ordered = list({p.href: p for p in ordered}.values())
        groups.append(
            {
                "slug": cfg["slug"],
                "title": cfg["title"],
                "description": cfg["description"],
                "count": len(ordered),
                "pages": ordered,
                "links": ordered[:4],
            }
        )
    return groups


def find_topic(groups: list[dict[str, object]], slug: str) -> dict[str, object]:
    for group in groups:
        if group.get("slug") == slug:
            return group
    available = ", ".join(str(group.get("slug", "")) for group in groups)
    raise ValueError(f"Unknown topic '{slug}'. Available topics: {available}")


LOG_ENTRY_RE = re.compile(r"^## \[(?P<date>\d{4}-\d{2}-\d{2})\]\s+(?P<kind>[^|]+)\|\s*(?P<title>.+)$")


def sort_log_entries_newest_first(body_md: str) -> str:
    lines = body_md.splitlines(keepends=True)
    prefix: list[str] = []
    entries: list[tuple[str, int, str]] = []
    current_date = ""
    current_index = -1
    current_lines: list[str] = []

    def flush_current() -> None:
        if current_lines:
            entries.append((current_date, current_index, "".join(current_lines)))

    for line_index, line in enumerate(lines):
        m = LOG_ENTRY_RE.match(line.strip())
        if m:
            flush_current()
            current_date = m.group("date")
            current_index = line_index
            current_lines = [line]
            continue
        if current_lines:
            current_lines.append(line)
        else:
            prefix.append(line)
    flush_current()

    entries.sort(key=lambda entry: (entry[0], entry[1]), reverse=True)
    return "".join(prefix) + "".join(entry for _, _, entry in entries)


